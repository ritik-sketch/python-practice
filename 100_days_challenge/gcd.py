#greatest common divisor
#Euclidean Algorithm - do numbs ka sbse bada divisor nikalne me ye use hoti h 
#example = 12 , 15 GCD = 3

a = 12
b = 15
while b != 0:
    a,b = b , a%b  #replace a with b, b with remainder 
    '''
    ड्राई रन: a = 12, b = 15
शुरुआत में, हमारे पास a = 12 और b = 15 है।

Iteration 1
while b != 0:: कंडीशन सही है क्योंकि 15 != 0 है।

a, b = b, a % b: यह Python में एक शानदार तरीका है दो वेरिएबल को एक साथ अपडेट करने का।

a की नई वैल्यू b की पुरानी वैल्यू (15) बन जाती है।

b की नई वैल्यू a को b से भाग देने पर मिलने वाला शेषफल (12 % 15) बन जाती है।

12 % 15 का शेषफल 12 होता है।

अब, a की नई वैल्यू 15 है और b की नई वैल्यू 12 है।

Iteration 2
while b != 0:: कंडीशन सही है क्योंकि 12 != 0 है।

a, b = b, a % b:

a की नई वैल्यू b की पुरानी वैल्यू (12) बन जाती है।

b की नई वैल्यू a को b से भाग देने पर मिलने वाला शेषफल (15 % 12) बन जाती है।

15 % 12 का शेषफल 3 होता है।

अब, a की नई वैल्यू 12 है और b की नई वैल्यू 3 है।

Iteration 3
while b != 0:: कंडीशन सही है क्योंकि 3 != 0 है।

a, b = b, a % b:

a की नई वैल्यू b की पुरानी वैल्यू (3) बन जाती है।

b की नई वैल्यू a को b से भाग देने पर मिलने वाला शेषफल (12 % 3) बन जाती है।

12 % 3 का शेषफल 0 होता है।

अब, a की नई वैल्यू 3 है और b की नई वैल्यू 0 है।

लूप का अंत
while b != 0:: कंडीशन अब गलत है क्योंकि b की वैल्यू 0 हो गई है। लूप रुक जाता है।

print(a): लूप रुकने के बाद, a की आखिरी वैल्यू 3 प्रिंट होती है, जो कि 12 और 15 का सबसे बड़ा सामान्य विभाजक (GCD) है।

यह एल्गोरिथम बहुत clever है क्योंकि यह बिना किसी अतिरिक्त वेरिएबल का उपयोग किए, बार-बार शेषफल निकालता है और वेरिएबल को अपडेट करता है, जिससे अंत में GCD मिल जाता है।
'''
print (a)